"""Task states for the GitHub Issue queue.

The markdown task registry remains the planning record. These states are the
execution projection on an approved Task Contract issue.
"""

from __future__ import annotations

BACKLOG = "BACKLOG"
READY = "READY"
CLAIMED = "CLAIMED"
IMPLEMENTING = "IMPLEMENTING"
PR_OPEN = "PR_OPEN"
CI_CHECK = "CI_CHECK"
INDEPENDENT_QA = "INDEPENDENT_QA"
READY_FOR_MERGE = "READY_FOR_MERGE"
MERGED = "MERGED"
DONE = "DONE"
BLOCKED = "BLOCKED"
NEEDS_CONTROLLER = "NEEDS_CONTROLLER"
FAILED = "FAILED"
BUDGET_HOLD = "BUDGET_HOLD"

STATUSES = (
    BACKLOG,
    READY,
    CLAIMED,
    IMPLEMENTING,
    PR_OPEN,
    CI_CHECK,
    INDEPENDENT_QA,
    READY_FOR_MERGE,
    MERGED,
    DONE,
    BLOCKED,
    NEEDS_CONTROLLER,
    FAILED,
    BUDGET_HOLD,
)

ACTIVE = {CLAIMED, IMPLEMENTING, PR_OPEN, CI_CHECK, INDEPENDENT_QA}
DEPENDENCY_SATISFIED = {MERGED, DONE}
LAUNCHABLE = {READY}

TRANSITIONS = {
    BACKLOG: {READY, BLOCKED, NEEDS_CONTROLLER},
    READY: {CLAIMED, BLOCKED, NEEDS_CONTROLLER, BUDGET_HOLD},
    CLAIMED: {IMPLEMENTING, BLOCKED, NEEDS_CONTROLLER, FAILED},
    IMPLEMENTING: {PR_OPEN, CI_CHECK, BLOCKED, NEEDS_CONTROLLER, FAILED},
    PR_OPEN: {CI_CHECK, BLOCKED, NEEDS_CONTROLLER},
    CI_CHECK: {INDEPENDENT_QA, IMPLEMENTING, BLOCKED, NEEDS_CONTROLLER},
    INDEPENDENT_QA: {READY_FOR_MERGE, IMPLEMENTING, BLOCKED, NEEDS_CONTROLLER},
    READY_FOR_MERGE: {NEEDS_CONTROLLER, BLOCKED},
    MERGED: {DONE},
    DONE: set(),
    BLOCKED: {READY, NEEDS_CONTROLLER},
    NEEDS_CONTROLLER: {READY, BLOCKED},
    FAILED: {READY, BLOCKED},
    BUDGET_HOLD: {READY, BLOCKED},
}


def can_transition(current: str, target: str) -> bool:
    if current == target:
        return True
    return target in TRANSITIONS.get(current, set())
